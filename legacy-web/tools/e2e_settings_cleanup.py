"""Browser test for the settings cleanup (phone landscape 844x390, touch).
Usage: python e2e_settings_cleanup.py <base_url> [shot_dir]   (serve www/ first). Exit 1 on any failure."""
import asyncio, json, sys
from playwright.async_api import async_playwright
BASE = sys.argv[1].rstrip('/'); OUT = (sys.argv[2].rstrip('/') + '/') if len(sys.argv) > 2 else None
fails = []
def ok(c, m):
    print(('PASS ' if c else 'FAIL ') + m)
    if not c: fails.append(m)
async def main():
  async with async_playwright() as p:
    b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', headless=True, args=['--use-gl=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'])
    c = await b.new_context(viewport={'width':844,'height':390}, device_scale_factor=2, is_mobile=True, has_touch=True)
    pg = await c.new_page(); errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    shot = lambda n: pg.screenshot(path=OUT + n) if OUT else asyncio.sleep(0)
    prefs = lambda: pg.evaluate("JSON.parse(localStorage.getItem('vn_p3d_prefs_v1')||'{}')")
    # old v1.5.33 prefs must still load
    await pg.goto(BASE + '/proto3d.html')
    await pg.evaluate("localStorage.setItem('vn_p3d_prefs_v1', JSON.stringify({view:'third',zoom:1,zoomSens:1.6,lookSens:1.2,quality:'auto',shadows:true,showFps:true,combatSet:false,combat:true,camMode:'follow'}))")
    await pg.reload(); await pg.wait_for_timeout(4000)
    ok(await pg.is_hidden('.vn-links a[href*="model-viewer"]'), 'title has no model gallery link')
    await shot('00-title.png')
    await pg.evaluate("document.getElementById('vnEnter')?.click()"); await pg.wait_for_timeout(6000)
    ok(not await pg.evaluate("(()=>{const f=document.getElementById('fps');return !!f && f.checkVisibility() && f.getBoundingClientRect().width>0})()"), 'FPS hidden by default (old save had it on)')
    await shot('10-ingame.png')
    await pg.tap('#vnMenuBtn'); await pg.wait_for_timeout(500)
    vis = await pg.evaluate("[...document.querySelectorAll('#vnQuickMenu .vn-quick-actions button')].filter(b=>b.offsetParent).map(b=>b.textContent.trim())")
    ok(vis == ['▶ Resume','⚔ Heroes','⌖ Travel','⚔ Multiplayer','⚙ Settings','⌂ Return to title'], 'menu is trimmed: ' + json.dumps(vis, ensure_ascii=False))
    for sel in ['#vnOwnerTools','#vnCoOwnerTools']:
      ok(not await pg.is_visible(sel), sel + ' not visible by default')
    await shot('11-menu.png')
    await pg.tap('#vnQuickTravel'); await pg.wait_for_timeout(300); ok(await pg.evaluate("document.getElementById('vnQuickWorld').open"), 'Travel opens world list')
    await pg.tap('#vnQuickMp'); await pg.wait_for_timeout(300); ok(await pg.evaluate("document.getElementById('vnQuickMultiplayer').open"), 'Multiplayer opens worlds')
    await shot('12-menu-multiplayer.png')
    await pg.evaluate("document.getElementById('vnQuickGear').open=true"); await pg.wait_for_timeout(300)
    ok('Fight mode' in (await pg.inner_text('#vnGearReadout')) or 'Weapon' in (await pg.inner_text('#vnGearReadout')), 'gear readout shown in menu')
    await shot('13-menu-gear.png')
    await pg.tap('#vnOpenSettings'); await pg.wait_for_timeout(2500)
    tabs = await pg.evaluate("[...document.querySelectorAll('#settingsPanel .vn-set-tab')].map(t=>t.textContent)")
    ok(tabs == ['Graphics','Controls','Gameplay'], 'three tabs: ' + str(tabs))
    ok(await pg.locator('#settingsPanel [data-set="owner-cheats"]').count() == 0, 'no owner/dev items before unlock')
    await shot('20-settings-graphics.png')
    await pg.select_option('#setQuality', 'low'); ok((await prefs()).get('quality') == 'low', 'Quality saves')
    await pg.tap('#settingsPanel [data-set="shadows"]'); ok((await prefs()).get('shadows') is False, 'Shadows toggles')
    await pg.tap('#settingsPanel [data-tab="controls"]'); await pg.wait_for_timeout(300); await shot('21-settings-controls.png')
    await pg.tap('#settingsPanel [data-set="view-first"]'); ok((await prefs()).get('view') == 'first', 'First person view')
    await pg.tap('#settingsPanel [data-set="view-third"]'); ok((await prefs()).get('view') == 'third', 'Third person view')
    await pg.tap('#settingsPanel [data-set="cam-free"]'); ok((await prefs()).get('camMode') == 'free', 'Camera follow off')
    await pg.tap('#settingsPanel [data-set="cam-follow"]'); ok((await prefs()).get('camMode') == 'follow', 'Camera follow on')
    ok(abs(float(await pg.input_value('#settingsPanel [data-set="camSens"]')) - 1.2) < 1e-6, 'merged slider shows old look sensitivity')
    await pg.evaluate("(()=>{const i=document.querySelector('#settingsPanel [data-set=\"camSens\"]');i.value='2';i.dispatchEvent(new Event('input'))})()")
    pr = await prefs(); ok(pr.get('lookSens') == 2 and pr.get('zoomSens') == 2, 'Camera sensitivity sets look + zoom')
    await pg.tap('#settingsPanel [data-set="editbtns"]'); await pg.wait_for_timeout(800)
    ok(await pg.evaluate("!!window.__vnHudEditor?.isEditing?.()"), 'Customize HUD opens editor'); await shot('22-hud-editor.png')
    await pg.evaluate("window.__vnHudEditor?.close?.(false)")
    await pg.evaluate("document.getElementById('setBtn').click()"); await pg.wait_for_timeout(800)
    await pg.tap('#settingsPanel [data-tab="gameplay"]'); await pg.wait_for_timeout(300); await shot('23-settings-gameplay.png')
    before = await pg.evaluate("!!window.__p3d?.fight?.on")
    await pg.tap('#settingsPanel [data-set="combat"]'); await pg.wait_for_timeout(2500)
    ok(await pg.evaluate("!!window.__p3d?.fight?.on") != before, 'Combat toggles fight mode')
    await pg.tap('#settingsPanel [data-set="combat"]'); await pg.wait_for_timeout(1500)
    # 5 taps on the visible About line -> hidden tab
    # Headless swiftshader taps are ~1.7 s apart (slower than the 2.5 s / 5-tap window), so send
    # quick real touch-type pointerup events in one go, as a phone finger would.
    taps = lambda n: pg.evaluate("n=>{const a=document.querySelector('#settingsPanel [data-vn-about]');for(let i=0;i<n;i++)a.dispatchEvent(new PointerEvent('pointerup',{bubbles:true,pointerType:'touch',isPrimary:true}))}", n)
    await pg.tap('#settingsPanel [data-vn-about]'); await taps(3); await pg.wait_for_timeout(3000)
    ok(await pg.locator('#settingsPanel [data-tab="hidden"]').count() == 0, '4 taps do not unlock')
    await taps(5); await pg.wait_for_timeout(1200)
    ok(await pg.locator('#settingsPanel [data-tab="hidden"]').count() == 1, '5 taps open the Owner & Dev tab')
    await shot('30-owner-dev.png')
    await pg.tap('#settingsPanel [data-set="showFps"]'); await pg.wait_for_timeout(600)
    ok(await pg.evaluate("(()=>{const f=document.getElementById('fps');return !!f && f.checkVisibility() && f.getBoundingClientRect().width>0})()"), 'Show FPS makes the counter visible')
    await pg.tap('#settingsPanel [data-set="showFps"]')
    await pg.tap('#settingsPanel [data-set="diagnostics"]'); await pg.wait_for_timeout(600)
    ok(await pg.evaluate("(()=>{const d=document.getElementById('diag');return !!d && getComputedStyle(d).display!=='none'})()"), 'Diagnostics opens')
    await shot('31-diagnostics.png'); await pg.evaluate("document.getElementById('diagBtn')?.click()")
    await pg.evaluate("document.getElementById('setBtn').click()"); await pg.wait_for_timeout(800)
    await pg.tap('#settingsPanel [data-set="coowner-tools"]'); await pg.wait_for_timeout(600)
    ok(await pg.is_visible('#vnCoOwnerPanel'), 'CoOwner Tools opens the CoOwner password gate'); await shot('32-coowner-gate.png')
    await pg.evaluate("document.querySelector('#vnCoOwnerPanel button[aria-label=\"Close CoOwner tools\"]')?.click()")
    await pg.evaluate("document.getElementById('setBtn').click()"); await pg.wait_for_timeout(800)
    await pg.tap('#settingsPanel [data-set="owner-cheats"]'); await pg.wait_for_timeout(1500)
    ok(await pg.evaluate("[...document.querySelectorAll('input[type=password]')].some(i=>i.offsetParent)"), 'Owner Cheats opens the owner password gate'); await shot('33-owner-gate.png')
    await pg.keyboard.press('Escape'); await pg.wait_for_timeout(400)
    # backtick also opens hidden tab (fresh page so unlock is not remembered)
    await pg.reload(); await pg.wait_for_timeout(4000); await pg.evaluate("document.getElementById('vnEnter')?.click()"); await pg.wait_for_timeout(5000)
    await pg.keyboard.press('`'); await pg.wait_for_timeout(1500)
    ok(await pg.locator('#settingsPanel [data-tab="hidden"]').count() == 1 and await pg.is_visible('#settingsPanel'), 'backtick opens Owner & Dev tab')
    await pg.evaluate("document.getElementById('setClose')?.click()")
    mdl = await pg.evaluate("localStorage.getItem('vn_model')||'blocky'")
    await pg.keyboard.press('`'); await pg.wait_for_timeout(1000)
    async with pg.expect_navigation(): await pg.tap('#settingsPanel [data-set="model-style"]')
    await pg.wait_for_timeout(1500)
    ok(await pg.evaluate("localStorage.getItem('vn_model')||'blocky'") != mdl, 'Model style switches')
    ok(not errs, 'no page errors: ' + '; '.join(errs[:3]))
    await b.close()
asyncio.run(main())
print('FAILURES:', len(fails)); sys.exit(1 if fails else 0)
